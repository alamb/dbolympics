#!/usr/bin/env python3
"""Emit per-database SQL from schema/schema.json.

  tools/emit_ddl.py --dialect duckdb                       # basic schema (default)
  tools/emit_ddl.py --dialect postgres --with fk,unique,check
  tools/emit_ddl.py --lookup-data                          # INSERTs for lookup tables
  tools/emit_ddl.py --rules                                # validation queries
  tools/emit_ddl.py --all                                  # regenerate schema/ddl/*

The basic schema is: tables, column types, NOT NULL, PRIMARY KEY. Everything
else (foreign keys, unique, check, defaults, indexes, comments) is metadata in
schema.json that can be switched on with --with; the data generator is
responsible for guaranteeing it.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema" / "schema.json"
DDL_DIR = ROOT / "schema" / "ddl"

FEATURES = ["fk", "unique", "check", "defaults", "indexes", "comments"]


class Dialect:
    name = "standard"
    supports = {"fk", "unique", "check", "defaults", "indexes", "comments"}

    def type(self, t: dict) -> str:
        n = t["name"]
        if n == "varchar":
            return f"varchar({t['length']})"
        if n == "decimal":
            return f"decimal({t['precision']},{t['scale']})"
        if n == "double":
            return "double precision"
        if n == "array":
            return f"{self.type(t['element'])} ARRAY"
        return n  # bigint integer smallint boolean date timestamp uuid json

    def ident(self, s: str) -> str:
        # always quoted: some column names (key) are keywords to some systems
        return f'"{s}"'


class Postgres(Dialect):
    name = "postgres"

    def type(self, t):
        if t["name"] == "json":
            return "jsonb"  # PostgreSQL's json type re-parses on every access
        return super().type(t)


class DuckDB(Dialect):
    name = "duckdb"


DIALECTS = {d.name: d for d in (Dialect(), Postgres(), DuckDB())}


def toposort(tables):
    """Parents before children (FK order), stable w.r.t. the file order."""
    pos = {t["name"]: i for i, t in enumerate(tables)}
    deps = {t["name"]: {fk["references"]["table"] for fk in t.get("foreign_keys", [])
                        if fk["references"]["table"] != t["name"]} for t in tables}
    done, order = set(), []
    while len(order) < len(tables):
        ready = [n for n in deps if n not in done and deps[n] <= done]
        if not ready:
            raise SystemExit(f"FK cycle among: {sorted(n for n in deps if n not in done)}")
        n = min(ready, key=pos.get)
        order.append(n); done.add(n)
    by = {t["name"]: t for t in tables}
    return [by[n] for n in order]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def emit_schema(doc, d: Dialect, feats: set[str]) -> str:
    unsupported = feats - d.supports
    if unsupported:
        raise SystemExit(f"{d.name} does not support: {sorted(unsupported)}")
    mod = {m["name"]: i for i, m in enumerate(doc["modules"])}
    tables = sorted(doc["tables"], key=lambda t: (mod[t["module"]], t["kind"] != "lookup"))
    tables = toposort(tables) if "fk" in feats else tables
    out = [f"-- generated by tools/emit_ddl.py from schema/schema.json -- do not edit",
           f"-- dialect: {d.name}; features: {', '.join(sorted(feats)) or 'basic (types, NOT NULL, PRIMARY KEY)'}",
           ""]
    module = None
    for t in tables:
        if t["module"] != module:
            module = t["module"]
            out.append(f"-- {'=' * 74}\n-- {module}\n-- {'=' * 74}\n")
        w = max(len(d.ident(c["name"])) for c in t["columns"])
        items = []
        for c in t["columns"]:
            s = f"{d.ident(c['name']):<{w}} {d.type(c['type'])}"
            if "defaults" in feats and "default" in c:
                s += f" DEFAULT {c['default']}"
            if not c["nullable"]:
                s += " NOT NULL"
            items.append(s)
        items.append(f"PRIMARY KEY ({', '.join(d.ident(c) for c in t['primary_key'])})")
        if "unique" in feats:
            for u in t.get("unique", []):
                pre = f"CONSTRAINT {u['name']} " if u.get("name") else ""
                items.append(f"{pre}UNIQUE ({', '.join(u['columns'])})")
        if "check" in feats:
            for ck in t.get("checks", []):
                pre = f"CONSTRAINT {ck['name']} " if ck.get("name") else ""
                items.append(f"{pre}CHECK ({ck['expr']})")
        if "fk" in feats:
            for fk in t.get("foreign_keys", []):
                pre = f"CONSTRAINT {fk['name']} " if fk.get("name") else ""
                r = fk["references"]
                items.append(f"{pre}FOREIGN KEY ({', '.join(fk['columns'])}) "
                             f"REFERENCES {r['table']} ({', '.join(r['columns'])})")
        out.append(f"CREATE TABLE {t['name']} (\n    " + ",\n    ".join(items) + "\n);\n")
    if "indexes" in feats:
        out.append("-- indexes (not part of the SQL standard)")
        names = set()
        for t in tables:
            for ix in t.get("indexes", []):
                nm = ix.get("name") or f"{t['name']}_{'_'.join(ix['columns'])}_idx"
                base, k = nm, 2
                while nm in names:
                    nm, k = f"{base}{k}", k + 1
                names.add(nm)
                out.append(f"CREATE INDEX {nm} ON {t['name']} ({', '.join(ix['columns'])});")
        out.append("")
    if "comments" in feats:
        out.append("-- comments (not part of the SQL standard)")
        for t in tables:
            if t.get("comment"):
                out.append(f"COMMENT ON TABLE {t['name']} IS {q(t['comment'])};")
            for c in t["columns"]:
                if c.get("comment"):
                    out.append(f"COMMENT ON COLUMN {t['name']}.{c['name']} IS {q(c['comment'])};")
        out.append("")
    return "\n".join(out)


def emit_lookup_data(doc) -> str:
    out = ["-- generated by tools/emit_ddl.py from schema/schema.json -- do not edit",
           "-- static rows of the lookup tables (former ENUM types); standard SQL", ""]
    for t in doc["tables"]:
        if t.get("rows"):
            cols = ", ".join(c["name"] for c in t["columns"])
            vals = ",\n    ".join("(" + ", ".join(q(v) if isinstance(v, str) else str(v) for v in r) + ")"
                                  for r in t["rows"])
            out.append(f"INSERT INTO {t['name']} ({cols}) VALUES\n    {vals};\n")
    return "\n".join(out)


def emit_rules(doc) -> str:
    out = ["-- generated by tools/emit_ddl.py from schema/schema.json -- do not edit",
           "-- Integrity rules that standard SQL constraints cannot express. Each query",
           "-- returns the VIOLATING rows; on valid data every query returns zero rows.", ""]
    for t in doc["tables"]:
        for r in t.get("rules", []):
            nm, tb = r.get("name") or t["name"], t["name"]
            if r["kind"] == "unique_where":
                cols = ", ".join(r["columns"])
                out.append(f"-- {nm}: at most one row per ({cols}) where {r['where']}\n"
                           f"SELECT {cols}, count(*) AS n FROM {tb} WHERE {r['where']} "
                           f"GROUP BY {cols} HAVING count(*) > 1;\n")
            elif r["kind"] == "no_overlap":
                k = " AND ".join(f"a.{c} = b.{c}" for c in r["key"])
                lo, hi = r["period"]
                inf = "TIMESTAMP '9999-12-31 00:00:00'"
                out.append(f"-- {nm}: {r['description']}\n"
                           f"SELECT a.id AS id_a, b.id AS id_b FROM {tb} a JOIN {tb} b ON {k} AND a.id < b.id\n"
                           f"  AND a.{lo} < COALESCE(b.{hi}, {inf}) AND b.{lo} < COALESCE(a.{hi}, {inf});\n")
            elif r["kind"] == "custom":
                out.append(f"-- {nm}: {r['description']}\n{r['violations_sql']};\n")
            else:
                raise SystemExit(f"unknown rule kind {r['kind']}")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dialect", choices=sorted(DIALECTS), default="standard")
    ap.add_argument("--with", dest="feats", default="",
                    help=f"comma-separated subset of {','.join(FEATURES)}, or 'all'")
    ap.add_argument("--lookup-data", action="store_true")
    ap.add_argument("--rules", action="store_true")
    ap.add_argument("--all", action="store_true", help="regenerate the committed files in schema/ddl/")
    ap.add_argument("-o", "--output")
    a = ap.parse_args()
    doc = json.loads(SCHEMA.read_text())
    if a.all:
        DDL_DIR.mkdir(exist_ok=True)
        for name, d in DIALECTS.items():
            (DDL_DIR / f"{name}.sql").write_text(emit_schema(doc, d, set()))
        (DDL_DIR / "duckdb_constraints.sql").write_text(
            emit_schema(doc, DIALECTS["duckdb"], {"fk", "unique", "check"}))
        (DDL_DIR / "lookup_data.sql").write_text(emit_lookup_data(doc))
        (DDL_DIR / "rules.sql").write_text(emit_rules(doc))
        print(f"wrote {', '.join(sorted(p.name for p in DDL_DIR.iterdir()))}", file=sys.stderr)
        return
    feats = set(FEATURES) if a.feats == "all" else {f for f in a.feats.split(",") if f}
    if feats - set(FEATURES):
        raise SystemExit(f"unknown features: {feats - set(FEATURES)}")
    if a.lookup_data:
        text = emit_lookup_data(doc)
    elif a.rules:
        text = emit_rules(doc)
    else:
        text = emit_schema(doc, DIALECTS[a.dialect], feats)
    if a.output:
        Path(a.output).write_text(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
