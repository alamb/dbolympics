//! Generates `$OUT_DIR/tables.rs` from schema/schema.json: one module per table with its
//! table id (`T`) and one constant per column index, e.g. `tables::orders::GRAND_TOTAL`.
use std::fmt::Write;

fn main() {
    println!("cargo:rerun-if-changed=schema/schema.json");
    let text = std::fs::read_to_string("schema/schema.json").expect("schema/schema.json");
    let doc: serde_json::Value = serde_json::from_str(&text).expect("valid JSON");
    let mut out = String::new();
    writeln!(out, "// generated by build.rs from schema/schema.json -- do not edit").unwrap();
    for (i, t) in doc["tables"].as_array().unwrap().iter().enumerate() {
        let name = t["name"].as_str().unwrap();
        writeln!(out, "#[allow(dead_code)]\npub mod r#{name} {{").unwrap();
        writeln!(out, "    pub const T: crate::schema::TableId = crate::schema::TableId({i});").unwrap();
        let cols = t["columns"].as_array().unwrap();
        for (j, c) in cols.iter().enumerate() {
            let c = c["name"].as_str().unwrap().to_uppercase();
            writeln!(out, "    pub const {c}: usize = {j};").unwrap();
        }
        writeln!(out, "    pub const NCOLS: usize = {};\n}}", cols.len()).unwrap();
    }
    let dst = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("tables.rs");
    std::fs::write(dst, out).unwrap();
}
